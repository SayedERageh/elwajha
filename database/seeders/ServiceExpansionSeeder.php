            $serviceData['service_category_id'] = $category->id;

            /*
            |--------------------------------------------------------------------------
            | Important:
            | updateOrCreate by slug only.
            | This does NOT delete old services.
            |--------------------------------------------------------------------------
            */

            Service::updateOrCreate(
                [
                    'slug' => $serviceData['slug'],
                ],
                $serviceData
            );
        }
    }
